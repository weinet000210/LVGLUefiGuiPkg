#!/usr/bin/env python3
## @file
#  Regenerate Library/LvglLib/LvglLib.inf from the LVGL submodule.
#
#  Every LVGL .c file is listed except backends that need hardware, an OS or
#  third-party libraries this package never enables. Everything listed is
#  still gated by lv_conf.h, so disabled features compile to empty objects.
#
#  Usage: python3 scripts/gen-lvgl-inf.py
#
#  Copyright (c) 2026, Niall Tseng. All rights reserved.<BR>
#  SPDX-License-Identifier: BSD-2-Clause-Patent
##

import os
import subprocess
import sys

PKG = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIB = os.path.join(PKG, "Library", "LvglLib")
SRC = os.path.join(LIB, "lvgl", "src")

EXCLUDED_DIRS = {
    # GPUs and display controllers
    "draw/dma2d", "draw/espressif", "draw/eve", "draw/nanovg", "draw/nema_gfx",
    "draw/nxp", "draw/opengles", "draw/renesas", "draw/sdl", "draw/sifli",
    "draw/vg_lite", "debugging/vg_lite_tvg",
    # Platform drivers (LVGLUefiGuiPkg has its own UEFI backends)
    "drivers",
    # Third-party libraries that need libc, C++ or an OS
    "libs/FT800-FT813", "libs/ffmpeg", "libs/freetype", "libs/gltf",
    "libs/gstreamer", "libs/libjpeg_turbo", "libs/libpng", "libs/libwebp",
    "libs/nanovg", "libs/rlottie", "libs/thorvg", "libs/vg_lite_driver",
    # Allocators and string functions we do not use
    "stdlib/clib", "stdlib/micropython", "stdlib/rtthread", "stdlib/uefi",
}
OSAL_KEEP = {"lv_os.c", "lv_os_none.c"}


def excluded(rel):
    parts = rel.split("/")
    for i in range(1, len(parts)):
        if "/".join(parts[:i]) in EXCLUDED_DIRS:
            return True
    if parts[0] == "osal" and parts[-1] not in OSAL_KEEP:
        return True
    return False


def main():
    files = []
    for root, _, names in os.walk(SRC):
        for name in names:
            if name.endswith(".c"):
                rel = os.path.relpath(os.path.join(root, name), SRC).replace(os.sep, "/")
                if not excluded(rel):
                    files.append("lvgl/src/" + rel)
    files.sort()

    version = subprocess.run(
        ["git", "-C", os.path.join(LIB, "lvgl"), "describe", "--tags"],
        capture_output=True, text=True, check=False).stdout.strip() or "unknown"

    out = []
    out.append("## @file")
    out.append("#  LvglLib - LVGL %s built as an EDK2 library (BASE)." % version)
    out.append("#")
    out.append("#  GENERATED by scripts/gen-lvgl-inf.py. Do not edit by hand; change the")
    out.append("#  script and rerun it after updating the lvgl submodule.")
    out.append("#")
    out.append("#  Copyright (c) 2026, Niall Tseng. All rights reserved.<BR>")
    out.append("#  SPDX-License-Identifier: BSD-2-Clause-Patent")
    out.append("#  LVGL itself is MIT licensed, see lvgl/LICENCE.txt.")
    out.append("#")
    out.append("##")
    out.append("")
    out.append("[Defines]")
    out.append("  INF_VERSION                    = 0x00010005")
    out.append("  BASE_NAME                      = LvglLib")
    out.append("  FILE_GUID                      = 6A0F9C1E-58B4-4C3B-9D2E-6E1C4B7A9F31")
    out.append("  MODULE_TYPE                    = BASE")
    out.append("  VERSION_STRING                 = %s" % version.lstrip("v"))
    out.append("  LIBRARY_CLASS                  = LvglLib")
    out.append("")
    out.append("[Sources]")
    out.append("  lv_conf.h")
    out.append("  lv_uefi_gui_assert.h")
    out.append("  lv_uefi_gui_inttypes.h")
    out.append("  lv_uefi_gui_limits.h")
    for f in files:
        out.append("  " + f)
    out.append("")
    out.append("[Packages]")
    out.append("  MdePkg/MdePkg.dec")
    out.append("  LVGLUefiGuiPkg/LVGLUefiGuiPkg.dec")
    out.append("")
    out.append("[LibraryClasses]")
    out.append("  CompilerIntrinsicsLib")
    out.append("")
    out.append("[BuildOptions]")
    out.append("  # Upstream code is compiled unmodified: keep warnings visible but not fatal")
    out.append("  # and silence the classes LVGL triggers by design. Calls to undeclared")
    out.append("  # functions stay fatal, and the link fails on any missing libc symbol.")
    out.append("  # -ffreestanding: use the compiler's own <stdint.h> etc., never libc's.")
    out.append("  # -U__linux__ ...: x86_64-linux-gnu-gcc predefines them, which would make")
    out.append("  # LVGL pick Linux code paths (e.g. /proc based idle time) in a UEFI image.")
    out.append("  GCC:*_*_*_CC_FLAGS  = -ffreestanding -U__linux__ -U__linux -Ulinux -U__unix__ -U__unix -Uunix -Werror=implicit-function-declaration -Wno-error -Wno-unused-parameter -Wno-unused-variable -Wno-unused-but-set-variable -Wno-sign-compare -Wno-missing-field-initializers -Wno-format")
    out.append("  MSFT:*_*_*_CC_FLAGS = /WX- /wd4100 /wd4189 /wd4204 /wd4244 /wd4245 /wd4267 /wd4018 /wd4389 /wd4701 /wd4703 /wd4706 /wd4146 /wd4221 /wd4310 /wd4334 /wd4456 /wd4457 /wd4459 /wd4127 /utf-8")
    out.append("")
    with open(os.path.join(LIB, "LvglLib.inf"), "w", newline="\n") as fh:
        fh.write("\n".join(out))
    print("LvglLib.inf: %d source files (LVGL %s)" % (len(files), version))
    return 0


if __name__ == "__main__":
    sys.exit(main())
